-- Simulador de examen de inglés - Script de creación para MariaDB 10.4 / MySQL
-- Crea la BD, tablas, restricciones y carga niveles + 80 preguntas con opciones.
-- Cargar con:  mysql -u root -p --default-character-set=utf8mb4 < simulador_ingles_mysql.sql
-- (el script puede reinicializarse sin borrar los datos persistentes)
-- =====================================================================
SET NAMES utf8mb4;
CREATE DATABASE IF NOT EXISTS simulador_ingles CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE simulador_ingles;

-- ---------- Catálogos ------------------------------------------------
CREATE TABLE niveles (
    nivel_id      TINYINT UNSIGNED NOT NULL AUTO_INCREMENT,
    nombre_nivel  VARCHAR(50) NOT NULL,              -- Básico / Intermedio / Avanzado
    orden         TINYINT UNSIGNED NOT NULL,         -- 1 = más bajo
    PRIMARY KEY (nivel_id),
    UNIQUE KEY ux_niveles_nombre (nombre_nivel),
    UNIQUE KEY ux_niveles_orden (orden)
) ENGINE=InnoDB;

CREATE TABLE usuarios (
    usuario_id      INT UNSIGNED NOT NULL AUTO_INCREMENT,
    nombre          VARCHAR(100) NOT NULL,
    correo          VARCHAR(150) NOT NULL,           -- identificador de login
    password_hash   VARCHAR(255) NOT NULL,           -- hash (werkzeug), nunca texto plano
    fecha_registro  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    rol             ENUM('alumno', 'administrador') NOT NULL DEFAULT 'alumno',
    PRIMARY KEY (usuario_id),
    UNIQUE KEY ux_usuarios_correo (correo)
) ENGINE=InnoDB;

