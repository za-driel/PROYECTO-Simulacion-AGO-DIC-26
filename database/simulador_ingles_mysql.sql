-- ---------- Banco de preguntas ---------------------------------------
CREATE TABLE preguntas (
    pregunta_id     INT UNSIGNED NOT NULL AUTO_INCREMENT,
    nivel_id        TINYINT UNSIGNED NOT NULL,
    texto_pregunta  VARCHAR(500) NOT NULL,
    imagen_url      VARCHAR(500) NULL,               -- opcional (apoyo visual)
    PRIMARY KEY (pregunta_id),
    UNIQUE KEY ux_preguntas_texto (texto_pregunta),
    KEY ix_preguntas_nivel (nivel_id),
    CONSTRAINT fk_preguntas_nivel FOREIGN KEY (nivel_id)
        REFERENCES niveles (nivel_id) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE opciones (
    opcion_id    INT UNSIGNED NOT NULL AUTO_INCREMENT,
    pregunta_id  INT UNSIGNED NOT NULL,
    letra        CHAR(1) NOT NULL,
    texto        VARCHAR(255) NOT NULL,
    es_correcta  TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (opcion_id),
    UNIQUE KEY ux_opciones_letra (pregunta_id, letra),
    CONSTRAINT fk_opciones_pregunta FOREIGN KEY (pregunta_id)
        REFERENCES preguntas (pregunta_id) ON DELETE CASCADE,
    CONSTRAINT ck_opciones_letra CHECK (letra IN ('a','b','c','d')),
    CONSTRAINT ck_opciones_correcta CHECK (es_correcta IN (0,1))
) ENGINE=InnoDB;

-- ---------- Simulador de práctica (20 preguntas, máx. 5 intentos) -----
CREATE TABLE intentos_practica (
    intento_practica_id  INT UNSIGNED NOT NULL AUTO_INCREMENT,
    usuario_id           INT UNSIGNED NOT NULL,
    numero_intento       TINYINT UNSIGNED NOT NULL,
    fecha_intento        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,   -- inicio
    fecha_fin            DATETIME NULL,                                  -- NULL = en curso
    calificacion         DECIMAL(5,2) NULL,
    aprobado             TINYINT(1) NULL,
    nivel_resultado_id   TINYINT UNSIGNED NULL,
    PRIMARY KEY (intento_practica_id),
    UNIQUE KEY ux_practica_usuario_num (usuario_id, numero_intento),
    CONSTRAINT fk_practica_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (usuario_id) ON DELETE CASCADE,
    CONSTRAINT fk_practica_nivel FOREIGN KEY (nivel_resultado_id)
        REFERENCES niveles (nivel_id),
    CONSTRAINT ck_practica_num CHECK (numero_intento BETWEEN 1 AND 5),
    CONSTRAINT ck_practica_calif CHECK (calificacion IS NULL OR calificacion BETWEEN 0 AND 100),
    CONSTRAINT ck_practica_aprob CHECK (aprobado IS NULL OR (calificacion IS NOT NULL AND aprobado = (calificacion >= 70)))
) ENGINE=InnoDB;

CREATE TABLE detalle_intentos_practica (
    detalle_practica_id  INT UNSIGNED NOT NULL AUTO_INCREMENT,
    intento_practica_id  INT UNSIGNED NOT NULL,
    pregunta_id          INT UNSIGNED NOT NULL,
    orden                TINYINT UNSIGNED NOT NULL,
    respuesta_dada       CHAR(1) NULL,               -- NULL = sin responder / tiempo agotado
    es_correcta          TINYINT(1) NULL,
    tiempo_respuesta     TINYINT UNSIGNED NULL,      -- segundos (0-60)
    fecha_presentada     DATETIME(3) NULL,           -- cuándo se mostró la pregunta (control del minuto en servidor)
    PRIMARY KEY (detalle_practica_id),
    UNIQUE KEY ux_det_practica_pregunta (intento_practica_id, pregunta_id),  -- no repetir pregunta
    UNIQUE KEY ux_det_practica_orden (intento_practica_id, orden),
    KEY ix_det_practica_pregunta (pregunta_id),
    CONSTRAINT fk_det_practica_intento FOREIGN KEY (intento_practica_id)
        REFERENCES intentos_practica (intento_practica_id) ON DELETE CASCADE,
    CONSTRAINT fk_det_practica_pregunta FOREIGN KEY (pregunta_id)
        REFERENCES preguntas (pregunta_id),
    CONSTRAINT ck_det_practica_orden CHECK (orden BETWEEN 1 AND 20),
    CONSTRAINT ck_det_practica_resp CHECK (respuesta_dada IS NULL OR respuesta_dada IN ('a','b','c','d')),
    CONSTRAINT ck_det_practica_tiempo CHECK (tiempo_respuesta IS NULL OR tiempo_respuesta <= 60)
) ENGINE=InnoDB;

-- ---------- Simulador final (40 preguntas, máx. 2 intentos) -----------
CREATE TABLE intentos_finales (
    intento_final_id     INT UNSIGNED NOT NULL AUTO_INCREMENT,
    usuario_id           INT UNSIGNED NOT NULL,
    numero_intento       TINYINT UNSIGNED NOT NULL,
    fecha_intento        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_fin            DATETIME NULL,
    calificacion         DECIMAL(5,2) NULL,
    aprobado             TINYINT(1) NULL,
    nivel_resultado_id   TINYINT UNSIGNED NULL,
    PRIMARY KEY (intento_final_id),
    UNIQUE KEY ux_final_usuario_num (usuario_id, numero_intento),
    CONSTRAINT fk_final_usuario FOREIGN KEY (usuario_id)
        REFERENCES usuarios (usuario_id) ON DELETE CASCADE,
    CONSTRAINT fk_final_nivel FOREIGN KEY (nivel_resultado_id)
        REFERENCES niveles (nivel_id),
    CONSTRAINT ck_final_num CHECK (numero_intento BETWEEN 1 AND 2),
    CONSTRAINT ck_final_calif CHECK (calificacion IS NULL OR calificacion BETWEEN 0 AND 100),
    CONSTRAINT ck_final_aprob CHECK (aprobado IS NULL OR (calificacion IS NOT NULL AND aprobado = (calificacion >= 70)))
) ENGINE=InnoDB;

CREATE TABLE detalle_intentos_finales (
    detalle_final_id   INT UNSIGNED NOT NULL AUTO_INCREMENT,
    intento_final_id   INT UNSIGNED NOT NULL,
    pregunta_id        INT UNSIGNED NOT NULL,
    orden              TINYINT UNSIGNED NOT NULL,
    respuesta_dada     CHAR(1) NULL,
    es_correcta        TINYINT(1) NULL,
    tiempo_respuesta   TINYINT UNSIGNED NULL,
    fecha_presentada   DATETIME(3) NULL,
    PRIMARY KEY (detalle_final_id),
    UNIQUE KEY ux_det_final_pregunta (intento_final_id, pregunta_id),
    UNIQUE KEY ux_det_final_orden (intento_final_id, orden),
    KEY ix_det_final_pregunta (pregunta_id),
    CONSTRAINT fk_det_final_intento FOREIGN KEY (intento_final_id)
        REFERENCES intentos_finales (intento_final_id) ON DELETE CASCADE,
    CONSTRAINT fk_det_final_pregunta FOREIGN KEY (pregunta_id)
        REFERENCES preguntas (pregunta_id),
    CONSTRAINT ck_det_final_orden CHECK (orden BETWEEN 1 AND 40),
    CONSTRAINT ck_det_final_resp CHECK (respuesta_dada IS NULL OR respuesta_dada IN ('a','b','c','d')),
    CONSTRAINT ck_det_final_tiempo CHECK (tiempo_respuesta IS NULL OR tiempo_respuesta <= 60)
) ENGINE=InnoDB;

